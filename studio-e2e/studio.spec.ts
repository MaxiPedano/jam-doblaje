import { test, expect } from '@playwright/test'
import { randomBytes } from 'node:crypto'

test('cuenta real, carga con tramos, separación IA, ajuste rápido y descarga privada', async ({ page, request }) => {
  const password = randomBytes(20).toString('hex')
  const fixture = await request.get('/api/studio/test-fixture')
  expect(fixture.ok()).toBe(true)
  await page.goto('/#/studio')
  await expect(page.getByRole('heading', { name: 'Crear la primera cuenta del equipo' })).toBeVisible()
  await page.getByLabel('Usuario del equipo', { exact: true }).fill('equipo-test')
  await page.getByLabel('Contraseña').fill(password)
  await page.getByLabel('Clave de instalación local').fill('studio-browser-setup-test-only')
  await page.getByRole('button', { name: 'Crear cuenta del equipo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sesión de equipo-test' })).toBeVisible()
  await expect(page.getByRole('radio', { name: /Solo el diálogo/ })).toBeChecked()
  await page.getByLabel('Video original', { exact: true }).setInputFiles({ name: 'synthetic.mp4', mimeType: 'video/mp4', buffer: await fixture.body() })
  await page.getByLabel(/^Tramos con diálogo/).fill('0:00-0:02')
  await page.getByRole('button', { name: 'Cargar y recortar el diálogo', exact: true }).click()
  await expect(page.getByText('Video recibido.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Comparar videos' })).toBeVisible({ timeout: 120000 })
  await expect(page.getByText('tramos: 0:00-0:02')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Comparar videos' })).toBeVisible()
  await page.getByRole('button', { name: 'Comparar videos' }).click()
  await expect(page.locator('.studio-comparison video')).toHaveCount(2)
  const output = page.locator('.studio-comparison video').nth(1)
  await expect.poll(() => output.evaluate((v: HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(1)

  await page.getByRole('button', { name: 'Ajustar tramos', exact: true }).click()
  const editor = page.locator('.studio-remix')
  await editor.getByLabel(/^Tramos con diálogo/).fill('0:00-0:01')
  await editor.getByRole('button', { name: 'Reprocesar con estos tramos', exact: true }).click()
  await expect(page.getByText('Ajuste en cola', { exact: false })).toBeVisible()
  await expect(page.getByText(/tramos: 0:00-0:01/)).toBeVisible({ timeout: 60000 })

  const downloadEvent = page.waitForEvent('download')
  const link = page.getByRole('link', { name: 'Descargar video sin diálogo' })
  const url = await link.getAttribute('href')
  await link.click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toMatch(/sin-voces\.mp4$/)
  expect(await download.failure()).toBeNull()
  expect((await request.get(url!)).status()).toBe(401)
  await page.getByRole('button', { name: 'Cerrar sesión del equipo' }).click()
  await expect(page.getByRole('heading', { name: 'Ingresar al equipo' })).toBeVisible()
  expect(await page.evaluate(async u => (await fetch(u)).status, url!)).toBe(401)

  // Modo voz: separación por hablante, escucha de muestras y quitar una voz.
  await page.getByLabel('Usuario del equipo', { exact: true }).fill('equipo-test')
  await page.getByLabel('Contraseña').fill(password)
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sesión de equipo-test' })).toBeVisible()
  await page.getByLabel('Video original', { exact: true }).setInputFiles({ name: 'synthetic-voz.mp4', mimeType: 'video/mp4', buffer: await fixture.body() })
  await page.getByRole('radio', { name: /Una sola voz/ }).check()
  await page.getByRole('button', { name: 'Cargar y separar las voces', exact: true }).click()
  await expect(page.getByText('Video recibido.', { exact: false })).toBeVisible()
  const vozCard = page.locator('.studio-job').filter({ hasText: 'synthetic-voz.mp4' })
  await expect(vozCard.getByText('Escuchar y elegir voz')).toBeVisible({ timeout: 150000 })
  await expect(vozCard.locator('.voice-card')).toHaveCount(2, { timeout: 60000 })
  await expect(vozCard.getByText('No encontré una segunda voz clara')).toBeVisible()
  await expect(vozCard.getByRole('button', { name: 'Ajustar tramos' })).toHaveCount(0)
  await vozCard.locator('.voice-card').first().getByRole('button', { name: 'Quitar esta voz', exact: true }).click()
  await expect(page.getByText('Cola para quitar la voz', { exact: false })).toBeVisible()
  await expect(vozCard.getByRole('link', { name: 'Descargar video sin la voz elegida' })).toBeVisible({ timeout: 60000 })
  await expect(vozCard.getByRole('button', { name: 'Quitar esta voz del resultado' })).toHaveCount(2)
  await vozCard.getByRole('button', { name: 'Comparar videos' }).click()
  await expect(vozCard.getByText('Sin la voz elegida · resultado estimado')).toBeVisible()
})
