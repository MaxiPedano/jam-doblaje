import { test, expect } from '@playwright/test'

test('carga del equipo, JSON, suscripción requerida, compartir y vencimiento', async ({ page, browser }) => {
  await page.route('https://drive.google.com/**', route => route.fulfill({ contentType: 'text/html', body: '<p>Reproductor simulado</p>' }))
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await expect(page.getByText('Los primeros doblajes están por llegar')).toBeVisible()
  await expect(page.getByRole('link', { name: 'Carga del equipo' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Simular vista del equipo' }).click()
  await page.getByRole('link', { name: 'Carga del equipo', exact: true }).click()
  await page.getByLabel('Título del doblaje', { exact: true }).fill('Doblaje ficticio')
  await page.getByLabel('Película', { exact: true }).fill('Película de prueba')
  await page.getByLabel('Género', { exact: true }).fill('Drama')
  await page.getByRole('combobox', { name: /^Popularidad/ }).selectOption('alta')
  await page.getByLabel('Enlace de archivo de Drive o identificador').fill('ID_FICTICIO_12345')
  await page.getByRole('button', { name: 'Agregar doblaje', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Doblaje agregado')
  await page.getByRole('button', { name: 'Editar Doblaje ficticio' }).click()
  await page.getByLabel('Título del doblaje', { exact: true }).fill('Doblaje editado')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar JSON' }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe('catalog.json')
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  const exported = Buffer.concat(chunks)
  const catalog = JSON.parse(exported.toString())
  expect(catalog.videos[0]).toMatchObject({ titulo: 'Doblaje editado', pelicula: 'Película de prueba', popularidad: 'alta' })
  await page.getByRole('button', { name: 'Eliminar Doblaje editado' }).click()
  await page.locator('input[type=file]').setInputFiles({ name: 'catalog.json', mimeType: 'application/json', buffer: exported })
  await expect(page.getByRole('status')).toContainText('Catálogo importado: 1')
  await page.locator('input[type=file]').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":2}') })
  await expect(page.getByRole('alert')).toContainText('No se importó')
  await page.getByRole('button', { name: 'Volver a vista suscriptor' }).click()
  await expect(page.getByRole('button', { name: 'Agregar doblaje', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Catálogo', exact: true }).click()
  await page.getByLabel('Buscar doblaje o película').fill('PELICULA')
  await expect(page.getByRole('heading', { name: 'Doblaje editado' })).toBeVisible()
  await page.getByLabel('Buscar doblaje o película').fill('no existe')
  await expect(page.getByRole('heading', { name: 'No encontramos doblajes' })).toBeVisible()
  await page.getByLabel('Buscar doblaje o película').fill('')
  await page.getByRole('button', { name: 'Agregar a favoritos: Doblaje editado' }).click()
  await page.getByRole('button', { name: '+ Lista', exact: true }).click()
  await page.getByRole('button', { name: 'Ver requisitos' }).click()
  await expect(page.getByRole('heading', { name: 'Necesitás una suscripción' })).toBeVisible()
  await expect(page.locator('.player iframe')).toHaveCount(0)
  const shareUrl = await page.getByLabel('Enlace para compartir').inputValue()
  await page.getByRole('link', { name: 'Suscripciones', exact: true }).click()
  await page.getByRole('button', { name: 'Simular suscripción Básico' }).click()
  await page.goto(shareUrl)
  await expect(page.getByRole('heading', { name: 'Este doblaje no está incluido en tu plan' })).toBeVisible()
  await expect(page.locator('.player iframe')).toHaveCount(0)
  await page.getByRole('link', { name: 'Suscripciones', exact: true }).click()
  await page.getByRole('button', { name: 'Simular suscripción Premium' }).click()
  await page.goto(shareUrl)
  await expect(page.locator('.player iframe')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.player iframe')).toHaveCount(1)
  // El destinatario tiene el mismo catálogo, pero no hereda la suscripción del remitente.
  const recipient = await browser.newContext()
  await recipient.addInitScript(c => localStorage.setItem('karaoke.catalog', JSON.stringify(c)), catalog)
  const recipientPage = await recipient.newPage()
  await recipientPage.goto(shareUrl)
  await expect(recipientPage.getByRole('heading', { name: 'Necesitás una suscripción' })).toBeVisible()
  await expect(recipientPage.locator('iframe, video')).toHaveCount(0)
  await recipient.close()
  await page.getByRole('link', { name: 'Suscripciones', exact: true }).click()
  await page.getByRole('button', { name: 'Simular vencimiento' }).click()
  await page.goto(shareUrl)
  await expect(page.locator('.player iframe')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Tu suscripción venció' })).toBeVisible()
  await page.reload()
  await expect(page.locator('.player iframe')).toHaveCount(0)
  await page.getByRole('link', { name: 'Mis doblajes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ver el siguiente' })).toBeEnabled()
})

test('vista celular y controles de equipo sin desbordamiento', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  for (const route of ['/', '/#/configuracion', '/#/acceso', '/#/mis-escenas']) {
    await page.goto(route)
    await expect(page.getByText('Modo demostración: sin cobros reales', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.getByRole('button', { name: 'Simular vista del equipo' }).click()
  await page.getByRole('link', { name: 'Carga del equipo', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Agregar doblaje', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('planes acumulativos, filtro, cambio de nivel y bloqueo HTML5', async ({ page }) => {
  const videos = ['baja', 'media', 'alta'].map((popularidad, i) => ({ id: `video-${i}`, titulo: `Doblaje ${popularidad}`, pelicula: 'Película ficticia', genero: 'Drama', popularidad, proveedor: 'html5', fuente: `https://example.invalid/${i}.mp4` }))
  await page.route('https://example.invalid/**', route => route.abort())
  await page.addInitScript(v => { if (!localStorage.getItem('karaoke.catalog')) localStorage.setItem('karaoke.catalog', JSON.stringify({ version: 1, videos: v })) }, videos)
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/#/doblaje/video-2')
  await expect(page.locator('video')).toHaveCount(0)
  for (const [plan, count] of [['Básico', 1], ['Estándar', 2], ['Premium', 3]] as const) {
    await page.getByRole('link', { name: 'Suscripciones', exact: true }).click()
    await page.getByRole('button', { name: `Simular suscripción ${plan}` }).click()
    await page.getByRole('link', { name: 'Catálogo', exact: true }).click()
    await page.getByLabel('Solo disponibles en mi suscripción activa').check()
    await expect(page.locator('.song-card')).toHaveCount(count)
  }
  await page.goto('/#/doblaje/video-2')
  await expect(page.locator('video')).toHaveCount(1)
  await page.getByRole('link', { name: 'Suscripciones', exact: true }).click()
  await page.getByRole('button', { name: 'Simular suscripción Básico' }).click()
  await expect(page.locator('video')).toHaveCount(0)
  await page.goto('/#/doblaje/video-2')
  await expect(page.getByRole('heading', { name: 'Este doblaje no está incluido en tu plan' })).toBeVisible()
  await page.goto('/#/doblaje/no-existe')
  await expect(page.getByRole('heading', { name: 'Doblaje no disponible' })).toBeVisible()
  await expect(page.locator('iframe, video')).toHaveCount(0)
})
